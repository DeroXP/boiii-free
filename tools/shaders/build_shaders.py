#!/usr/bin/env python3
"""Compiles the game client's HLSL shaders into C++ headers (docs/DESIGN.md
13.3: shaders ship precompiled, since upstream's "reduce stutter" option can
rename d3dcompiler_46.dll and the game has no shader compiler of its own).

Each src/client/xerces/upscale_shaders/<name>.hlsl becomes <name>.h next to
it: DXBC from the Windows SDK's fxc.exe (/O3, reflection and debug data
stripped) as a byte array named after the file. The headers are committed, so
a build needs no shader compiler; run this after changing a shader, and
`--check` to see that the committed headers are what the sources compile to
(the same fxc gives the same bytes).

  python -I tools/shaders/build_shaders.py [--check] [--fxc <path>]

fxc: --fxc, else FXC, else the newest Windows 10/11 SDK's x64 fxc.exe.
"""

import argparse
import os
import pathlib
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parents[2]
SHADERS = ROOT / "src" / "client" / "xerces" / "upscale_shaders"
INCLUDES = [ROOT / "deps" / "FidelityFX-FSR" / "ffx-fsr"]
SDK_BIN = pathlib.Path(r"C:\Program Files (x86)\Windows Kits\10\bin")


def find_fxc(given: str | None) -> pathlib.Path:
    for candidate in (given, os.environ.get("FXC")):
        if candidate:
            path = pathlib.Path(candidate)
            if not path.is_file():
                sys.exit(f"fxc not found: {path}")
            return path

    def version_key(path: pathlib.Path) -> tuple[int, ...]:
        try:
            return tuple(int(part) for part in path.parent.parent.name.split("."))
        except ValueError:
            return (0,)

    found = sorted(SDK_BIN.glob("10.*/x64/fxc.exe"), key=version_key)
    if not found:
        sys.exit("fxc.exe not found: install the Windows SDK, or pass --fxc")
    return found[-1]


def profile(name: str) -> str:
    if name.endswith("_vs"):
        return "vs_5_0"
    if name.endswith("_ps"):
        return "ps_5_0"
    if name.endswith("_cs"):
        return "cs_5_0"
    sys.exit(f"{name}.hlsl: the name must end in _vs, _ps or _cs")


def compile_one(fxc: pathlib.Path, source: pathlib.Path) -> bytes:
    with tempfile.TemporaryDirectory() as temp:
        out = pathlib.Path(temp) / "out.dxbc"
        command = [str(fxc), "/nologo", "/T", profile(source.stem), "/E", "main", "/O3",
                   "/Qstrip_reflect", "/Qstrip_debug", "/Qstrip_priv", "/WX", "/Fo", str(out)]
        for folder in INCLUDES:
            command += ["/I", str(folder)]
        command.append(str(source))
        result = subprocess.run(command, capture_output=True, text=True)
        if result.returncode != 0:
            sys.exit(f"{source.name}: fxc failed\n{result.stdout}{result.stderr}")
        return out.read_bytes()


def header(source: pathlib.Path, code: bytes, sdk: str) -> str:
    lines = [
        f"// Generated by tools/shaders/build_shaders.py from {source.name} (fxc from",
        f"// Windows SDK {sdk}, {profile(source.stem)}, /O3). Do not edit: change the",
        "// .hlsl file and run the script again.",
        "#pragma once",
        "",
        f"inline constexpr unsigned char {source.stem}[] = {{",
    ]
    for start in range(0, len(code), 12):
        chunk = code[start:start + 12]
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in chunk) + ",")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true",
                        help="compare the committed headers instead of writing them")
    parser.add_argument("--fxc", help="the fxc.exe to use")
    args = parser.parse_args()
    fxc = find_fxc(args.fxc)
    sdk = fxc.parent.parent.name
    stale = []
    for source in sorted(SHADERS.glob("*.hlsl")):
        text = header(source, compile_one(fxc, source), sdk)
        target = source.with_suffix(".h")
        if args.check:
            old = target.read_text(encoding="utf-8") if target.is_file() else ""
            # The SDK version in the comment may differ; the bytes may not.
            if old.split("#pragma once", 1)[-1] != text.split("#pragma once", 1)[-1]:
                stale.append(target.relative_to(ROOT).as_posix())
        else:
            target.write_bytes(text.encode("utf-8"))
            print(f"wrote {target.relative_to(ROOT).as_posix()} ({len(text)} bytes of text)")
    if stale:
        print("not what the sources compile to: " + ", ".join(stale))
        return 1
    if args.check:
        print("shader headers match their sources")
    return 0


if __name__ == "__main__":
    sys.exit(main())
